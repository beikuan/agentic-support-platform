CREATE TABLE IF NOT EXISTS support_ticket (
 id VARCHAR(36) PRIMARY KEY, booking_number VARCHAR(32) NOT NULL,
 first_name VARCHAR(100) NOT NULL, last_name VARCHAR(100) NOT NULL,
 request_text VARCHAR(2000) NOT NULL, status VARCHAR(32) NOT NULL,
 proposed_action VARCHAR(32), recommendation VARCHAR(2000),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS support_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id VARCHAR(36) NOT NULL, actor VARCHAR(100) NOT NULL,
 action VARCHAR(80) NOT NULL, detail VARCHAR(2000),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
